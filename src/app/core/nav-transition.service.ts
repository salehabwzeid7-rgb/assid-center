import { Injectable, inject } from '@angular/core';
import { NavigationEnd, NavigationStart, Router } from '@angular/router';

/**
 * مسارات التبويبات الخمسة في الشريط السفليّ، بترتيب ظهورها فيه — مصدر واحد
 * يستعمله الشريط نفسه (لتقرير ظهوره) وحاسب نوع الانتقال أدناه (لتقرير أسلوب
 * الحركة بين تبويب وآخر). كانت هذه القائمة محصورة داخل `BottomNavComponent`،
 * فنقلها إلى هنا يمنع نسختين متباعدتين تصفان الشيء نفسه.
 */
export const TAB_PATHS: string[] = ['/', '/circles', '/students', '/sard', '/profile'];

/**
 * نوع انتقال الشاشة:
 *  • `forward` — دفعة إلى الداخل (فتح تفصيل/نموذج، هرميّ): انزلاق أفقيّ كامل.
 *  • `back`    — سحب الدفعة السابقة (رجوع هرميّ): نفس الانزلاق معكوسًا تمامًا.
 *  • `cross`   — تبديل بين تبويبين شقيقين لا علاقة هرميّة بينهما (الرئيسية ↔
 *    الحلقات ↔ الطلّاب ↔ سرد واختبار ↔ الحساب): تلاشٍ متقاطع خفيف بدل الانزلاق —
 *    التبويبات ليست في تسلسل «فتح/إغلاق» واحد، فانزلاقها كصفحات هرميّة كان يوحي
 *    بعلاقة أب/ابن غير موجودة، والتلاشي هو النمط المعياريّ لتبديل التبويبات في
 *    التطبيقات الأصليّة (شريط تبويبات iOS/Android)، وأرخص حوسبيًّا أيضًا.
 */
export type NavDirection = 'forward' | 'back' | 'cross';

/**
 * نوع انتقال الشاشات — يكتب `data-nav="forward|back|cross"` على `<html>`
 * قبل كلّ تنقّل، فتقرأه أنماط View Transitions في `styles.css`.
 *
 * لماذا يُحسَب النوع أصلًا: انزلاق بجهة واحدة دائمًا يشعر المستخدم بأنّه
 * «يغوص» حتى وهو راجع للخلف — وهو بالضبط ما يجعل انتقالات الويب تبدو غير
 * أصليّة. الجهة الصحيحة هي أهمّ ما يميّز الإحساس الأصليّ عن الانزلاق المزخرف.
 *
 * التطبيق RTL دائمًا (لا يقلب اتجاهه إطلاقًا)، فالجهات هنا مكتوبة بمنطق RTL
 * صراحةً: **التقدّم** = الشاشة الجديدة تدخل من اليسار والقديمة تنزاح يمينًا،
 * و**الرجوع** (في `styles.css`) عكس ذلك حرفيًّا — إطارًا بإطار، لا مجرّد
 * "جهة مقابلة": أيّ فارق في المقدار أو الطبقة بين الاتّجاهين هو ما يُحسّ
 * كتعثّر أو دقّة عند الرجوع، فالرجوع الصحيح هو نفس حركة الدفعة مُشغَّلة للخلف.
 */
@Injectable({ providedIn: 'root' })
export class NavTransitionService {
  private readonly router = inject(Router);
  private path = this.router.url.split(/[?#]/)[0];

  init(): void {
    this.router.events.subscribe((e) => {
      if (e instanceof NavigationStart) {
        // يُكتب الاتّجاه عند البدء لا عند الانتهاء، لأنّ المتصفّح يلتقط لقطة
        // الشاشة قبل تغيّر الـDOM مباشرةً — فأيّ تأخير يجعل الانزلاق يبدأ بالجهة السابقة.
        const to = e.url.split(/[?#]/)[0];
        document.documentElement.dataset['nav'] = this.direction(
          this.path,
          to,
          e.navigationTrigger === 'popstate',
        );
      } else if (e instanceof NavigationEnd) {
        // المسار المرجعيّ يُحدّث عند **نجاح** التنقّل فقط، وبالمسار بعد أيّ
        // تحويل. تحديثه عند البدء يُفسِد حساب الاتّجاه التالي كلّما ألغى حارِس التنقّل
        // أو حوّله (مثلاً authGuard يردّ الزائر إلى /login): يُخزّن وجهة لم تُفتَح قطّ.
        this.path = e.urlAfterRedirects.split(/[?#]/)[0];
      }
    });
  }

  /**
   * يحسم النوع بترتيب أولويّة واضح:
   *  ١) بين تبويبين شقيقين مختلفين → `cross` دائمًا، بصرف النظر عن السبب
   *     (نقرة أو حتى popstate نادرة بينهما) — العلاقة بين المسارين هي ما
   *     تحدّد نوع الحركة، لا كيفيّة وصول التنقّل.
   *  ٢) زرّ الرجوع (نظام أو متصفّح) يصل دائمًا كـ popstate — أوثق إشارة على
   *     الرجوع الهرميّ، فله الأولويّة على أيّ استنتاج آخر من المسارات.
   *  ٣) من شاشة داخليّة إلى تبويب (بلا popstate) → رجوع أيضًا (صعود إلى جذر
   *     التبويب — مثل الضغط على «الحلقات» من داخل تفاصيل حلقة).
   *  ٤) ما عدا ذلك → تقدّم (فتح تفصيل أو نموذج جديد).
   */
  private direction(from: string, to: string, isPopstate: boolean): NavDirection {
    const fromTab = TAB_PATHS.indexOf(from);
    const toTab = TAB_PATHS.indexOf(to);
    if (fromTab >= 0 && toTab >= 0 && fromTab !== toTab) return 'cross';
    if (isPopstate) return 'back';
    if (toTab >= 0) return 'back';
    return 'forward';
  }
}
